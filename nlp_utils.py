def clean_text(text):
    text = text.lower()
    text = re.sub(r'[^\w\s]', '', text)
    return text.strip()

X_text = []
y = []

for intent, intent_data in BOT_CONFIG['intents'].items():
    for example in intent_data['examples']:
        X_text.append(clean_text(example))
        y.append(intent)

vectorizer = TfidfVectorizer(analyzer='char_wb', ngram_range=(2, 4))
X = vectorizer.fit_transform(X_text)
clf = LinearSVC(dual=False)
clf.fit(X, y)

dialogues_dataset = []

def load_dialogues():
    """Загружает очищенный dialogues.txt в оперативную память"""
    global dialogues_dataset
    try:
        import os
        if os.path.exists('dialogues.txt'):
            with open('dialogues.txt', 'r', encoding='utf-8') as f:
                content = f.read()
            blocks = content.split('\n\n')
            for block in blocks:
                lines = [line.strip() for line in block.split('\n') if line.strip()]
                if len(lines) >= 2:
                    q = lines[0].replace('-', '').strip()
                    a = lines[1].replace('-', '').strip()
                    if q and a:
                        dialogues_dataset.append((clean_text(q), a))
            print(f"База болталки dialogues.txt успешно загружена! Пар: {len(dialogues_dataset)}")
    except Exception as e:
        print(f"Ошибка при загрузке dialogues.txt: {e}")

load_dialogues()

def get_intent_with_keywords(text):
    # 1. Сначала пробуем ML-модель
    intent = get_intent(text)
    
    # 2. Если ML не нашел интент, ищем по ключевым словам
    if not intent:
        text_lower = text.lower()
        for intent_name, data in BOT_CONFIG['intents'].items():
            for example in data['examples']:
                if example.lower() in text_lower:
                    return intent_name
    return intent

def get_intent(text):
    text_clean = clean_text(text)
    if not text_clean:
        return None
    intent = clf.predict(vectorizer.transform([text_clean]))[0]
    decision = clf.decision_function(vectorizer.transform([text_clean]))[0]

    if max(decision) > 0.1: 
        return intent
    return None

def get_dialogue_fallback(text, current_topic=None):
    """Поиск близкого по смыслу вопроса в датасете через расстояние Левенштейна"""
    text_clean = clean_text(text)
    if not text_clean or not dialogues_dataset:
        return None
        
    best_match_answer = None
    min_distance = 1000
    
    for question, answer in dialogues_dataset:
        distance = nltk.edit_distance(text_clean, question)
        
        # Если тема совпадает, уменьшаем дистанцию (приоритет)
        if current_topic and current_topic in question:
            distance -= 2 
            
        if distance < min_distance and distance <= 6:
            min_distance = distance
            best_match_answer = answer
            
    return best_match_answer

def check_specific_shoe_request(text):
    """Проверяет, упомянул ли пользователь конкретный тип обуви из словаря"""
    t = text.lower()
    for key, formal_name in SUBCATEGORY_MAPPING.items():
        if key in t:
            return formal_name
    return None


def process_message(text, allow_ad=False, topic=None, last_bot_msg=None):
    intent = "unknown"
    answer = None

    # Шаг 1. КЛАССИФИКАТОР (Сначала пытаемся понять нормальный ответ на фразу)
    detected_intent = get_intent_with_keywords(text)
    
    if detected_intent and detected_intent in BOT_CONFIG.get('intents', {}):
        intent = detected_intent
        responses = BOT_CONFIG['intents'][intent].get('responses', [])
        if responses:
            if intent == 'buy_shoes' and len(responses) > 1:
                answer = responses[1]
            else:
                answer = responses[0]
            
            # Защита от повторения
            if answer == last_bot_msg and len(responses) > 1:
                answer = responses[1] if answer == responses[0] else responses[0]
            if answer == last_bot_msg:
                answer = "Кстати, это интересный момент! Но давай обсудим что-то еще. О чем ты хочешь поговорить?"

    # Шаг 2. Если интент не определен, пробуем базу болталки
    if not answer:
        chit_chat_answer = get_dialogue_fallback(text, current_topic=topic)
        if chit_chat_answer and chit_chat_answer != last_bot_msg:
            intent = "chit_chat"
            answer = chit_chat_answer

    # Шаг 3. Если совсем глухо — берем базовую заглушку
    if not answer:
        intent = "unknown"
        fallback = random.choice([
            "Понимаю! А чем ты тогда увлекаешься в свободное время?",
            "Ясно. А о чем тогда хочешь поболтать?",
            "Хорошо, давай сменим тему. Расскажешь что-нибудь интересное?"
        ])
        if fallback == last_bot_msg:
            fallback = "Интересная мысль! Расскажи об этом поподробнее?"
        answer = fallback

    # Шаг 4. УМНАЯ НАВТИВНАЯ РЕКЛАМА (Добавляется хвостом к базовому ответу)
    if allow_ad:
        text_lower = text.lower()
        # Генерируем контекстную подводку в зависимости от текущей темы диалога
        if topic == 'sports' or any(w in text_lower for w in ["спорт", "волейбол", "футбол", "бег", "тренировка"]):
            ad_transition = (
                "\n\nКстати, про спорт! Для отличных результатов и безопасных тренировок "
                "очень важна правильная фиксация и амортизация стопы. У нас в магазине как раз "
                "появились технологичные кроссовки со скидкой! Не хочешь взглянуть? 👟"
            )
        elif topic == 'movies' or any(w in text_lower for w in ["кино", "фильм", "сериал", "комедия", "аниме"]):
            ad_transition = (
                "\n\nКстати, пока смотришь хороший фильм или сериал, лучше всего устроиться с комфортом. "
                "А для долгих прогулок после кино идеальная обувь — это база. У нас сейчас как раз "
                "распродажа стильных кед и кроссовок для города! Заглянешь в каталог? 🎬👟"
            )
        elif any(w in text_lower for w in ["книг", "читаю"]):
            ad_transition = (
                "\n\nКстати, читать приятнее всего в уютной атмосфере, а вот для "
                "походов в книжные магазины или библиотеку точно понадобится удобная пара. У нас сейчас "
                "действуют отличные скидки на комфортные городские модели! Присмотрим что-нибудь? 📚"
            )
        elif topic == 'weather_talk' or topic == 'specific_weather':
            ad_transition = (
                "\n\nКстати, погода за окном бывает непредсказуемой, поэтому "
                "очень важно держать ноги в тепле и сухости. У нас сейчас отличные скидки на качественную обувь "
                "для любой погоды. Посмотрим ассортимент? ☁️👢"
            )
        else:
            # Универсальная подводка, если тема нейтральная
            ad_transition = f"\n\n{BOT_CONFIG['ad_phrase']}"
        
        # Склеиваем человеческий ответ и нативную рекламу
        answer = answer + ad_transition
        intent = "ad"

    return intent, answer